#!/usr/bin/env bash
# VEDA installer :: stage 7 -- make every path machine-local.
#
# Two jobs:
#
#  1. Write veda_paths.json, which src/config.py reads to find the four
#     interpreters, the BLAST binaries and the container images. This replaces
#     the /home/jrf-1/anaconda3/... literals that used to be in config.py.
#
#  2. Patch the six files that carry absolute paths of their own and are read
#     by the tools themselves, not by Python:
#
#       netMHCpan-4.2/netMHCpan        setenv NMHOME, setenv TMPDIR
#       netMHCIIpan-4.3/netMHCIIpan    setenv NMHOME
#       gibbscluster-2.0/gibbscluster  setenv GIBBS
#       algpred2/envfile               BLASTP, BLASTDB, MERCI, MOTIFS
#       toxinpred2/envfile             BLASTP, BLASTDB, MERCI, MOTIFS
#       ifnepitope2-main/envfile       BLASTP, BLASTDB
#
#     The workers rewrite the three envfiles at run time too, but they are
#     patched here so the tools also work when driven straight from a shell.
#
# The original of every patched file is kept alongside it as *.veda-orig.

veda::configure() {
    stage_header "Configuration"

    veda::_cfg_write_paths
    veda::_cfg_patch_wrappers
    veda::_cfg_patch_envfiles
    veda::_cfg_data_dirs
    log_ok "configuration written"
}

# --- veda_paths.json --------------------------------------------------------

veda::_cfg_write_paths() {
    local dest="$VEDA_APP_DIR/veda_paths.json"

    local blastp makeblastdb deeploc2 tcsh_bin perl_bin r_bin docker_bin
    blastp=$(env_bin veda-tools blastp)
    makeblastdb=$(env_bin veda-tools makeblastdb)
    deeploc2=$(env_bin veda-ui deeploc2)
    tcsh_bin=$(command -v tcsh || true)
    perl_bin=$(command -v perl || true)
    r_bin=$(command -v Rscript || true)
    docker_bin=$(command -v docker || true)

    [[ -x "$blastp" ]] || blastp=$(command -v blastp || true)
    [[ -x "$makeblastdb" ]] || makeblastdb=$(command -v makeblastdb || true)
    [[ -x "$deeploc2" ]] || deeploc2=$(command -v deeploc2 || true)

    log_info "writing ${dest##*/}"
    atomic_write "$dest" <<EOF
{
  "schema": 1,
  "_comment": "Generated by installer/lib/configure.sh. Machine-local; do not commit. Re-create with ./install.sh --only configure",
  "generated": "$(date '+%Y-%m-%dT%H:%M:%S%z')",
  "host": "$(hostname 2>/dev/null || echo unknown)",
  "veda_home": "$VEDA_HOME",
  "app_dir": "$VEDA_APP_DIR",
  "tools_dir": "$VEDA_TOOLS_DIR",
  "mamba_root": "$VEDA_MAMBA_ROOT",
  "tmpdir": "$VEDA_HOME/tmp",
  "python": {
    "ui": "$(env_python veda-ui)",
    "tools": "$(env_python veda-tools)",
    "tmhmm": "$(env_python veda-tmhmm)",
    "ifn": "$(env_python veda-ifn)"
  },
  "bin": {
    "blastp": "$blastp",
    "makeblastdb": "$makeblastdb",
    "deeploc2": "$deeploc2",
    "tcsh": "$tcsh_bin",
    "perl": "$perl_bin",
    "rscript": "$r_bin",
    "docker": "$docker_bin"
  },
  "docker": {
    "vaxign_image": "e4ong1031/vaxign-ml:latest",
    "deeptmhmm_image": "biolib/dtu-deeptmhmm:latest",
    "available": $( [[ "${VEDA_DOCKER_OK:-0}" != 0 ]] && echo true || echo false )
  }
}
EOF
    log_ok "wrote $dest"

    # Second copy in VEDA_HOME so config.py can still resolve paths if the
    # project directory is moved or the file is deleted by a git clean.
    mkdir -p "$VEDA_HOME"
    cp -f "$dest" "$VEDA_HOME/veda_paths.json"
    log_debug "mirrored to $VEDA_HOME/veda_paths.json"
}

# --- tcsh wrappers ----------------------------------------------------------

veda::_cfg_patch_wrappers() {
    local tmpdir="$VEDA_HOME/tmp"
    mkdir -p "$tmpdir"

    local f
    # NetMHCpan 4.2
    f="$VEDA_TOOLS_DIR/netMHCpan-4.2/netMHCpan"
    if [[ -f "$f" ]]; then
        setenv_patch "$f" NMHOME "$VEDA_TOOLS_DIR/netMHCpan-4.2" && log_ok "patched netMHCpan NMHOME"
        # TMPDIR sits inside an `if` block, so only patch when the line exists.
        setenv_patch "$f" TMPDIR "$tmpdir" >/dev/null 2>&1 && log_debug "patched netMHCpan TMPDIR"
        chmod u+x "$f"
    else
        log_warn "netMHCpan wrapper not found; skipping (tool not installed)"
    fi

    # NetMHCIIpan 4.3
    f="$VEDA_TOOLS_DIR/netMHCIIpan-4.3/netMHCIIpan"
    if [[ -f "$f" ]]; then
        setenv_patch "$f" NMHOME "$VEDA_TOOLS_DIR/netMHCIIpan-4.3" && log_ok "patched netMHCIIpan NMHOME"
        setenv_patch "$f" TMPDIR "$tmpdir" >/dev/null 2>&1 && log_debug "patched netMHCIIpan TMPDIR"
        chmod u+x "$f"
    else
        log_warn "netMHCIIpan wrapper not found; skipping (tool not installed)"
    fi

    # GibbsCluster 2.0
    f="$VEDA_TOOLS_DIR/gibbscluster-2.0/gibbscluster"
    if [[ -f "$f" ]]; then
        setenv_patch "$f" GIBBS "$VEDA_TOOLS_DIR/gibbscluster-2.0" && log_ok "patched gibbscluster GIBBS"
        chmod u+x "$f"
        # Seq2Logo / Rpath are left empty on purpose: the pipeline drives
        # Seq2Logo itself through backend/seq2logo_runner.py, and setting them
        # here would make GibbsCluster emit its own logos as a side effect.
    else
        log_warn "gibbscluster wrapper not found; skipping (tool not installed)"
    fi
}

# --- envfiles ---------------------------------------------------------------

veda::_cfg_patch_envfiles() {
    local blastp; blastp=$(env_bin veda-tools blastp)
    [[ -x "$blastp" ]] || blastp=$(command -v blastp || echo blastp)

    veda::_write_envfile algpred2 \
        "$blastp" \
        "$VEDA_TOOLS_DIR/algpred2/Database/data" \
        "$VEDA_TOOLS_DIR/algpred2/progs/MERCI_motif_locator.pl" \
        "$VEDA_TOOLS_DIR/algpred2/Database/pos_ige_motifs.txt"

    veda::_write_envfile toxinpred2 \
        "$blastp" \
        "$VEDA_TOOLS_DIR/toxinpred2/Database/data" \
        "$VEDA_TOOLS_DIR/toxinpred2/progs/MERCI_motif_locator.pl" \
        "$VEDA_TOOLS_DIR/toxinpred2/Database/pos_motif.txt"

    # IFNEpitope2's envfile carries only BLASTP and BLASTDB.
    veda::_write_envfile ifnepitope2-main \
        "$blastp" \
        "$VEDA_TOOLS_DIR/ifnepitope2-main/Database"
}

veda::_write_envfile() {
    local dir=$1 blastp=$2 blastdb=$3 merci=${4:-} motifs=${5:-}
    local path="$VEDA_TOOLS_DIR/$dir"
    [[ -d "$path" ]] || { log_debug "skipping envfile for missing $dir"; return 0; }

    local f="$path/envfile"
    backup_once "$f"
    {
        printf 'BLASTP:%s\n' "$blastp"
        printf 'BLASTDB:%s\n' "$blastdb"
        [[ -n "$merci" ]]  && printf 'MERCI:%s\n' "$merci"
        [[ -n "$motifs" ]] && printf 'MOTIFS:%s\n' "$motifs"
    } | atomic_write "$f"
    log_ok "wrote $dir/envfile"
}

# --- runtime directories ----------------------------------------------------

veda::_cfg_data_dirs() {
    local d
    for d in "$VEDA_APP_DIR/data" "$VEDA_APP_DIR/data/projects" \
             "$VEDA_APP_DIR/data/results" "$VEDA_APP_DIR/logs" \
             "$VEDA_HOME/tmp" "$VEDA_HOME/cache"; do
        mkdir -p "$d"
    done
    log_ok "data, log and cache directories in place"
}
