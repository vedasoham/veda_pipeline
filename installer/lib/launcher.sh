#!/usr/bin/env bash
# VEDA installer :: stage 8 -- the `veda` launcher.
#
# The launcher matters more than it looks. Several workers invoke their tool by
# bare name (deeploc2, streamlit) and inherit the parent's PATH, so VEDA must
# always start with veda-ui/bin in front. Starting the app by hand with the
# wrong interpreter is the single most common way this pipeline breaks.

veda::launcher_install() {
    stage_header "Launcher"

    # The command is named after VEDA_HOME, so a side-by-side trial install
    # (VEDA_HOME=~/.veda-test) becomes `veda-test` and cannot clobber the
    # `veda` command, symlink or desktop entry of a real install.
    VEDA_CMD=$(basename "$VEDA_HOME"); VEDA_CMD=${VEDA_CMD#.}
    [[ -z "$VEDA_CMD" ]] && VEDA_CMD=veda
    if [[ "$VEDA_CMD" != veda ]]; then
        log_info "this install uses VEDA_HOME=$VEDA_HOME"
        log_info "its command will be '$VEDA_CMD', keeping any existing 'veda' intact"
    fi

    veda::_launcher_script
    veda::_launcher_path_hint
    veda::_launcher_desktop
}

veda::_launcher_script() {
    local dest="$VEDA_HOME/bin/$VEDA_CMD"
    mkdir -p "$VEDA_HOME/bin"

    cat >"$dest" <<EOF
#!/usr/bin/env bash
# VEDA launcher -- generated by the VEDA installer on $(date '+%Y-%m-%d').
# Regenerate with:  ./install.sh --only launcher
set -Eeuo pipefail

export VEDA_HOME="$VEDA_HOME"
VEDA_APP_DIR="$VEDA_APP_DIR"
VEDA_MAMBA_ROOT="$VEDA_MAMBA_ROOT"
VEDA_UI_ENV="\$VEDA_MAMBA_ROOT/envs/veda-ui"
EOF

    # Generated from the single VEDA_SCRUB_VARS definition in probe.sh, so the
    # launcher and the probe report can never disagree about what is scrubbed.
    cat >>"$dest" <<EOF

# --- environment hygiene ---------------------------------------------------
# Unset what an activated Anaconda, or a user's shell profile, would otherwise
# leak into every VEDA worker process. installer/lib/probe.sh documents why
# each of these is hostile to an isolated install; the short version is that
# they redirect Python's import path, Perl's module path, TLS trust, or pip's
# install target away from the environment VEDA built.
unset ${VEDA_SCRUB_VARS[*]}
EOF

    cat >>"$dest" <<'EOF'

if [[ ! -x "$VEDA_UI_ENV/bin/streamlit" ]]; then
    printf 'VEDA is not fully installed: %s is missing.\n' "$VEDA_UI_ENV/bin/streamlit" >&2
    printf 'Run the installer again from %s\n' "$VEDA_APP_DIR" >&2
    exit 1
fi

# Drop path entries that would defeat the isolation.
#
#   * An EMPTY entry means "the current directory". In PATH that means a file
#     called `python` in whatever folder the app was started from could run
#     instead of ours; in LD_LIBRARY_PATH a stray .so in that folder gets
#     loaded. VEDA extracts downloaded archives and runs from user project
#     folders, so neither is acceptable.
#   * Another conda/anaconda prefix. VEDA's own environments come first, but a
#     tool invoked by bare name that VEDA does not ship would otherwise be
#     found in Anaconda, and then run against Anaconda's libraries.
#   * A system CUDA in LD_LIBRARY_PATH. It takes precedence over the CUDA
#     libraries bundled inside the PyTorch wheel, which is a common cause of
#     "torch installed fine but cannot see the GPU", and of cuBLAS/cuDNN
#     version errors. Set VEDA_KEEP_SYSTEM_CUDA=1 to keep it.
#
# Only VEDA's own subprocesses are affected; your interactive shell is not.
_veda_filter_path() {
    local kind=$1 raw=$2 out='' entry
    local IFS=:
    for entry in $raw; do
        [ -n "$entry" ] || continue
        case $entry in
            "$VEDA_MAMBA_ROOT"/*|"$VEDA_HOME"/*) ;;
            *anaconda3/*|*miniconda3/*|*miniforge3/*|*mambaforge/*|*/condabin|*/condabin/*)
                continue ;;
            */cuda*/lib*|*/cuda*/lib64/*)
                [ "$kind" = ld ] && [ "${VEDA_KEEP_SYSTEM_CUDA:-0}" != 1 ] && continue ;;
        esac
        out="${out:+$out:}$entry"
    done
    printf '%s' "$out"
}

# veda-ui/bin must lead: workers call `deeploc2` by bare name.
# ${x:+:$x} and not ":$x": appending a colon to an empty result would put an
# empty entry back, which is the thing we just removed.
_veda_rest=$(_veda_filter_path path "$PATH")
export PATH="$VEDA_UI_ENV/bin:$VEDA_HOME/bin${_veda_rest:+:$_veda_rest}"
unset _veda_rest

if [ -n "${LD_LIBRARY_PATH:-}" ]; then
    LD_LIBRARY_PATH=$(_veda_filter_path ld "$LD_LIBRARY_PATH")
    if [ -n "$LD_LIBRARY_PATH" ]; then export LD_LIBRARY_PATH; else unset LD_LIBRARY_PATH; fi
fi

# Load-bearing. A conda env still consults ~/.local/lib/pythonX.Y/site-packages,
# and it comes BEFORE the env's own site-packages on sys.path -- so anything
# installed there with `pip install --user` silently overrides every version
# VEDA pins. This one line is what makes the environments actually isolated,
# and it propagates to every worker subprocess.
export PYTHONNOUSERSITE=1

# The DTU tcsh wrappers and the MERCI Perl scripts mis-handle non-UTF-8
# locales, and a machine with no locale set at all is common on servers.
case "${LC_ALL:-${LC_CTYPE:-${LANG:-}}}" in
    *UTF-8*|*utf8*|*UTF8*) ;;
    *) export LC_ALL=C.UTF-8 LANG=C.UTF-8 ;;
esac

# Keep scratch files and multi-GB model caches out of the system /tmp and the
# user's home root.
export TMPDIR="${TMPDIR:-$VEDA_HOME/tmp}"
export TORCH_HOME="$VEDA_HOME/cache/torch"
export HF_HOME="$VEDA_HOME/cache/huggingface"
mkdir -p "$TMPDIR" "$TORCH_HOME" "$HF_HOME"

# Streamlit writes telemetry and config under $HOME by default; contain it.
export STREAMLIT_BROWSER_GATHER_USAGE_STATS=false

usage() {
    cat <<'USAGE'
VEDA -- immuno-epitope analysis pipeline

  veda                 start the web interface (default)
  veda run [args...]   start it, passing extra flags to streamlit
  veda doctor          check the installation and every tool
  veda shell           open a shell inside the veda-ui environment
  veda python          start the veda-ui python interpreter
  veda paths           print the resolved tool and interpreter paths
  veda version         show versions
  veda help            this text

Examples:
  veda --server.port 8502      run on a different port
  veda run --server.headless true   no browser auto-open
USAGE
}

cmd="${1:-run}"
case "$cmd" in
    run)
        shift || true
        cd "$VEDA_APP_DIR/src"
        exec streamlit run main.py "$@"
        ;;
    doctor)
        shift || true
        exec "$VEDA_APP_DIR/veda-doctor" "$@"
        ;;
    shell)
        cd "$VEDA_APP_DIR"
        printf 'veda-ui environment active. Type exit to leave.\n'
        exec "${SHELL:-/bin/bash}"
        ;;
    python)
        shift || true
        cd "$VEDA_APP_DIR/src"
        exec "$VEDA_UI_ENV/bin/python" "$@"
        ;;
    paths)
        if [[ -f "$VEDA_APP_DIR/veda_paths.json" ]]; then
            cat "$VEDA_APP_DIR/veda_paths.json"
        else
            printf 'veda_paths.json not found; run: ./install.sh --only configure\n' >&2
            exit 1
        fi
        ;;
    version|--version|-V)
        printf 'VEDA launcher\n'
        printf '  app      : %s\n' "$VEDA_APP_DIR"
        printf '  python   : %s\n' "$("$VEDA_UI_ENV/bin/python" -V 2>&1 || echo unavailable)"
        printf '  streamlit: %s\n' "$(streamlit version 2>/dev/null | head -1 || echo unavailable)"
        ;;
    help|--help|-h)
        usage
        ;;
    -*)
        # Bare streamlit flags: treat as `veda run <flags>`.
        cd "$VEDA_APP_DIR/src"
        exec streamlit run main.py "$@"
        ;;
    *)
        printf 'Unknown command: %s\n\n' "$cmd" >&2
        usage >&2
        exit 2
        ;;
esac
EOF

    chmod +x "$dest"
    log_ok "launcher written to $dest"

    # Symlink into ~/.local/bin, which is on PATH for most desktop sessions.
    local user_bin="$HOME/.local/bin"
    mkdir -p "$user_bin"
    if ln -sfn "$dest" "$user_bin/$VEDA_CMD"; then
        log_ok "linked $user_bin/$VEDA_CMD -> $dest"
    else
        log_warn "could not create $user_bin/$VEDA_CMD"
    fi
}

veda::_launcher_path_hint() {
    local user_bin="$HOME/.local/bin"
    case ":$PATH:" in
        *":$user_bin:"*) log_ok "$user_bin is already on your PATH"; return 0 ;;
    esac

    log_warn "$user_bin is not on your PATH, so '$VEDA_CMD' will not be found yet"

    # Append a guarded block to the user's shell rc, once.
    local rc
    if [[ -n "${ZSH_VERSION:-}" || "${SHELL:-}" == *zsh ]]; then rc="$HOME/.zshrc"; else rc="$HOME/.bashrc"; fi

    if [[ -f "$rc" ]] && grep -q 'VEDA launcher PATH' "$rc"; then
        log_ok "PATH entry already present in ${rc##*/}"
        return 0
    fi

    if confirm "Add $user_bin to your PATH in ${rc##*/}?" y; then
        {
            printf '\n# --- VEDA launcher PATH (added by the VEDA installer) ---\n'
            printf 'case ":$PATH:" in *":%s:"*) ;; *) PATH="%s:$PATH" ;; esac\n' "$user_bin" "$user_bin"
            printf 'export PATH\n'
        } >>"$rc"
        log_ok "updated ${rc##*/}"
        log_info "run 'source $rc' or open a new terminal to pick it up"
    else
        log_info "start VEDA with the full path instead: $VEDA_HOME/bin/$VEDA_CMD"
    fi
}

veda::_launcher_desktop() {
    local apps="$HOME/.local/share/applications"
    local icon="$VEDA_APP_DIR/resources/logo.png"
    mkdir -p "$apps"

    [[ -f "$icon" ]] || icon="applications-science"

    # A trial install gets its own entry and a distinguishable name.
    local disp="VEDA"
    [[ "$VEDA_CMD" != veda ]] && disp="VEDA (${VEDA_CMD#veda-})"

    atomic_write "$apps/$VEDA_CMD.desktop" <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=$disp
GenericName=Immuno-epitope analysis pipeline
Comment=Epitope prediction, MHC binding, localisation and immunogenicity analysis
Exec=$VEDA_HOME/bin/$VEDA_CMD run
Icon=$icon
Terminal=true
Categories=Science;Biology;Education;
Keywords=epitope;MHC;immunology;proteomics;bioinformatics;
StartupNotify=true
EOF
    chmod 644 "$apps/$VEDA_CMD.desktop"
    log_ok "desktop entry written to $apps/$VEDA_CMD.desktop"

    have update-desktop-database && update-desktop-database "$apps" 2>/dev/null || true
    return 0
}
